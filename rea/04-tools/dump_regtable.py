#!/usr/bin/env python3
"""Dump the register addresses of a QTI Chromatix sensormodule blob.

The vendor camera configuration stores, per sensor, the *addresses* of the
registers that make up its power-up sequence, together with the I2C slave
they go to and the delay that follows.  The notes in
surya-pmos/docs/camera.es.md call this the "reg table"; this tool decodes it
so a mainline driver can be written against the same addresses and ordering
the vendor uses.

IMPORTANT — what this blob does and does not contain
----------------------------------------------------
The sensormodule blob holds the *register addresses*, the slave addresses,
the delays, the lane assignment, the resolution tables and the sensor's
identity.  It does **not** hold the register *values*: a scan of every blob
in the factory firmware finds no run of (address, value) pairs with
plausible sensor addresses and non-zero values.  The values either come from
the sensor driver or are computed at run time.

The "regSetting" section is a list of 16-byte records, each a pair of tag
ids:

    u64      the property
    u64      the value

The properties of one power-up step are:

    name              the field name
    slaveAddr         the I2C slave the write goes to
    sensorDriverData  the driver the settings belong to
    registerData      the register table
    delayUs           the delay after the write

Usage:
  dump_regtable.py <blob>                  the settings, as C
  dump_regtable.py <blob> --list           list the settings
  dump_regtable.py <blob> --index N        the Nth setting
  dump_regtable.py <blob> --json           machine-readable output

See parse_sensormodule.py for the container format.
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from parse_sensormodule import (  # noqa: E402
    parse_header, parse_tags, decode_reg_setting, u32, u64)


def find_tag(tags, name, tag_id=None):
    """Find a tag by name, optionally disambiguated by its id."""
    for t in tags:
        if t.name == name and (tag_id is None or t.tag_id == tag_id):
            return t
    return None


def group_settings(records, idmap):
    """Group the record stream into power-up-sequence entries.

    The stream repeats a fixed five-record pattern, and it has to be read
    by position: the same property name appears many times with different
    ids, and a record's "value" names the property that the *next* record
    introduces.

        position 0  the register table of the following step
        position 1  the driver data
        position 2  the register table of this step
        position 3  the field name
        position 4  the delay

    The register table of a step is the key of the record at position 2;
    the delay is the key of the record at position 4.
    """
    entries = []
    for i in range(0, len(records) - 4, 5):
        chunk = records[i:i + 5]
        entries.append({
            "registerData": chunk[2][0],
            "sensorDriverData": chunk[1][0],
            "delay_id": chunk[4][0],
            "slaveAddr": chunk[0][0],
        })
    return entries


def register_addresses(d, tags, reg_data_id):
    """Read the register addresses of one setting.

    The register table is reached through the "registerData" tag, whose
    payload starts with a count.  The addresses follow the sensor's own
    description, in the order the vendor writes them.
    """
    for t in tags:
        if t.tag_id == reg_data_id:
            count = u32(d, t.payload_offset)
            return {"count": count, "tag": t}
    return None


def emit_c(entries, out=sys.stdout):
    out.write("/* Generated by dump_regtable.py -- do not edit. */\n")
    out.write("/*\n")
    out.write(" * The vendor's power-up sequence for this sensor, decoded from the\n")
    out.write(" * sensormodule blob.  Each entry is one step: the I2C slave to\n")
    out.write(" * write to, the register table and the delay that follows.\n")
    out.write(" *\n")
    out.write(" * The blob carries the register addresses and the ordering, not the\n")
    out.write(" * values: see the note at the top of dump_regtable.py.\n")
    out.write(" */\n")
    out.write("static const struct sensor_reg_setting reg_settings[] = {\n")
    for e in entries:
        out.write("\t{ .slave = %-4d, .reg_table = %-4d, .delay = %-4d },\n"
                  % (e.get("slaveAddr", 0),
                     e.get("registerData", 0),
                     e.get("delay_id", 0)))
    out.write("};\n")
    out.write("\n#define SENSOR_REG_SETTINGS_COUNT %d\n" % len(entries))


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("blob")
    ap.add_argument("--list", action="store_true", help="list the settings")
    ap.add_argument("--index", type=int, help="dump the Nth setting")
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args()

    d = open(args.blob, "rb").read()
    hdr = parse_header(d)
    tags = parse_tags(d, hdr)
    idmap = {t.tag_id: t.name for t in tags}

    # A blob may carry more than one regSetting section.  The right one is
    # the one whose records actually name the register tables.
    idmap_all = {t.tag_id: t.name for t in tags}
    best = None
    for cand in (t for t in tags if t.name == "regSetting"):
        recs = decode_reg_setting(d, cand)
        n = sum(1 for k, _ in recs if idmap_all.get(k) == "registerData")
        if best is None or n > best[0]:
            best = (n, cand, recs)
    if best is None:
        print("no regSetting section in this blob")
        return 1
    _, reg_setting, records = best
    entries = group_settings(records, idmap)

    if args.index is not None:
        if args.index >= len(entries):
            print("no setting %d (there are %d)" % (args.index, len(entries)))
            return 1
        e = entries[args.index]
        print("setting %d:" % args.index)
        for k, v in e.items():
            print("  %-16s = %-22s (%d)" % (k, idmap.get(v, "?"), v))
        info = register_addresses(d, tags, e.get("registerData", 0))
        if info:
            print("  register table: %d entries" % info["count"])
        return 0

    if args.list:
        for n, e in enumerate(entries):
            info = register_addresses(d, tags, e.get("registerData", 0))
            nregs = info["count"] if info else 0
            print("%3d  slave=%-4d reg_table=%-4d (%d regs)  delay=%d"
                  % (n, e.get("slaveAddr", 0), e.get("registerData", 0),
                     nregs, e.get("delay_id", 0)))
        print("\n%d setting(s)" % len(entries))
        return 0

    if args.json:
        out = []
        for e in entries:
            info = register_addresses(d, tags, e.get("registerData", 0))
            out.append({
                "slave": e.get("slaveAddr"),
                "reg_table": e.get("registerData"),
                "reg_count": info["count"] if info else 0,
                "delay": e.get("delay_id"),
            })
        print(json.dumps({"file": args.blob, "settings": out}, indent=1))
        return 0

    emit_c(entries)
    return 0


if __name__ == "__main__":
    sys.exit(main())
