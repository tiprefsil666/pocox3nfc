#!/usr/bin/env python3
"""Emit the register tables of a sensormodule blob as C.

The camera notes in surya-pmos/docs/camera.es.md refer to a tool that
"dumps a register table from the blob as C".  This is it.

The blob gives, for each step of a sensor's power-up sequence, the register
table to write and how many registers it has.

WHAT THIS TOOL DOES NOT YET DO
-----------------------------
The addresses of each table live in the payload pool, interleaved with the
other sections, and the framing between one table and the next is not yet
established.  The addresses are visible in the pool (for the IMX682 blob:
0x034c, 0x034e, 0x0340, 0x0342, 0x0202, 0x0204 and the clock registers
0x4050, 0x3ff0, 0x0492), but the tool cannot yet tell where one table ends
and the next begins, so it reports the count and the section rather than
guessing at the entries.

The vendor's own parser is the authority on that framing: it lives in
vendor/lib64/hw/camera.qcom.so (CamX), in
camximagesensormoduledatamanager.cpp.  That binary is 6.4 MB and the REA
analysis of it did not finish within the tool's time budget.

The output is a C array of the steps, ready to be pasted into a driver.

Usage:
  dump_reg_table.py <blob>              every table, as C
  dump_reg_table.py <blob> --index N    the Nth table
  dump_reg_table.py <blob> --json       machine-readable output
"""
import argparse
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from parse_sensormodule import (  # noqa: E402
    parse_header, parse_tags, decode_reg_setting, decode_register_table, u32)


def find_reg_setting(d, tags):
    """Pick the regSetting whose records actually name the register tables."""
    idmap = {t.tag_id: t.name for t in tags}
    best = None
    for cand in (t for t in tags if t.name == "regSetting"):
        recs = decode_reg_setting(d, cand)
        n = sum(1 for k, _ in recs if idmap.get(k) == "registerData")
        if best is None or n > best[0]:
            best = (n, cand, recs)
    return best


def collect_tables(d, tags):
    """Return the register tables, in the order the power-up sequence uses."""
    best = find_reg_setting(d, tags)
    if best is None:
        return []
    _, _, recs = best

    idmap = {t.tag_id: t.name for t in tags}
    tables = []
    for i in range(0, len(recs) - 4, 5):
        chunk = recs[i:i + 5]
        reg_id = chunk[2][0]
        if idmap.get(reg_id) != "registerData":
            continue
        tag = next((t for t in tags if t.tag_id == reg_id), None)
        if tag is None:
            continue
        count = u32(d, tag.payload_offset)
        tables.append({
            "id": reg_id,
            "count": count,
            "registers": decode_register_table(d, tag),
        })
    return tables


def emit_c(tables, out=sys.stdout):
    out.write("/* Generated by dump_reg_table.py -- do not edit. */\n")
    out.write("/*\n")
    out.write(" * The register tables of the sensor's power-up sequence, decoded from\n")
    out.write(" * the vendor's sensormodule blob.\n")
    out.write(" */\n")
    for n, t in enumerate(tables):
        out.write("\n/* table %d: %d registers */\n" % (n, t["count"]))
        if t["registers"]:
            out.write("static const struct sensor_reg reg_table_%d[] = {\n" % n)
            for addr, value in t["registers"]:
                out.write("\t{ 0x%04x, 0x%08x },\n" % (addr, value))
            out.write("};\n")
        else:
            out.write("/* the entries of this table are not extracted yet;\n"
                      " * see the note at the top of this file. */\n")
    out.write("\n#define SENSOR_REG_TABLE_COUNT %d\n" % len(tables))


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("blob")
    ap.add_argument("--index", type=int)
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args()

    d = open(args.blob, "rb").read()
    hdr = parse_header(d)
    tags = parse_tags(d, hdr)
    tables = collect_tables(d, tags)

    if args.index is not None:
        if args.index >= len(tables):
            print("no table %d (there are %d)" % (args.index, len(tables)))
            return 1
        t = tables[args.index]
        if args.json:
            print(json.dumps(t, indent=1))
        else:
            print("/* table %d: %d registers */" % (args.index, t["count"]))
            for addr, value in t["registers"]:
                print("  0x%04x = 0x%04x" % (addr, value))
        return 0

    if args.json:
        print(json.dumps({"file": args.blob, "tables": tables}, indent=1))
        return 0

    emit_c(tables)
    return 0


if __name__ == "__main__":
    sys.exit(main())
